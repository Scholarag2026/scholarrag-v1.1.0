"""Build a blind annotation package for the HSS test set and the real-claims set
(argparse copy of build_sheet_v2.py).

Same method as build_sheet_v2.py (see its own docstring for the full rationale):
opaque ids, a passage independently retrieved from the cited paper's own cached text by
scoring one-to-three sentence windows against the claim, an explicit no-match marker when
no window clears the threshold, and an explicit withheld-evidence marker for items whose
cited DOI is null. The construction category and the expected label, when they exist, are
written only to the withheld key, never to the sheet or the index.

Unlike build_sheet_v2.py, this script does **not** write the rubric (``INSTRUCTIONS_v3.md``
is authored directly, once, in the same commit that adds this script, so a later
``--suffix v3`` run of this script can never overwrite the file whose digest the round-3
gate pins), and it does **not** write per-annotator copies of the sheet (those are made,
unmodified, once labelling starts).

Every path, the shuffle seed, the opaque-id prefix and the output filename prefixes are
CLI flags, so the same script builds both the 60-item HSS round-3 test sheet and the
26-item real-claims sheet, and reproduces the round-2 HSS sheet byte for byte when pointed
at the round-2 inputs with ``--suffix v2`` and the round-2 seed (used only for the
regression test in evaluation/tests/test_claims_annotation_v3.py; the real round-2 files
are frozen and are never regenerated by this script in normal use).

Inputs (read only), all paths given on the command line:
  --claims           one JSON object per line: item_id, rule, expected (a list of labels,
                      or null/absent when no expected label exists), claim,
                      original_sentence, alteration, source_doi, chunk_doi, chunk_index,
                      title, authors, built_at (optional)
  --sources          optional: a JSON list of {doi, year, ...} records, used to look up the
                      cited paper's publication year; when omitted (or the doi is not in
                      it), the year falls back to the item's own "year" or "cited_year"
                      field, then to "n.d."
  --fulltext-dir      directory of cached paper texts, one {doi_to_filename(doi)}.json per
                      paper, each {chunks: [{section, text}, ...], ...}
  --fulltext-rel-dir  the same directory, written repo-relative into the index file

Outputs, written under --out-dir (default: this folder):
  {key-prefix}_{suffix}.csv     withheld key: ann_id, item_id, and, only when at least one
                                 item carries a non-null expected label, construction_category,
                                 expected_label, built_at
  {sheet-prefix}_{suffix}.csv   the blind sheet (UTF-8 BOM)
  source_texts_index_{suffix}.json   {ann_id: {cited_paper_doi, paths: [...]}}

Run with plain ``python`` (stdlib only). Example, the round-3 HSS test sheet:
  python build_sheet_v3.py \\
      --claims ../hss_test_v3_claims.jsonl --sources ../hss_test_v3_sources.json \\
      --fulltext-dir ../data/hss_test_v3_fulltext \\
      --fulltext-rel-dir evaluation/claims/data/hss_test_v3_fulltext \\
      --suffix v3 --seed 20260907 --expected-count 60
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import random
import re

BASE_DIR = os.path.dirname(os.path.abspath(__file__))

MATCH_THRESHOLD = 0.15
MAX_PASSAGE_CHARS = 700
NO_MATCH_MARKER = "No matching passage found in the cited paper (best overlap below threshold)"
WITHHELD_MARKER = "Evidence withheld: no passage or paper text is available for this item"

STOPWORDS = {
    "a", "an", "the", "and", "or", "but", "of", "to", "in", "on", "at", "for", "with", "as",
    "is", "are", "was", "were", "be", "been", "being", "that", "this", "these", "those", "it",
    "its", "by", "from", "which", "who", "whom", "their", "they", "he", "she", "his", "her",
    "we", "our", "you", "your", "i", "not", "no", "do", "does", "did", "has", "have", "had",
    "will", "would", "can", "could", "should", "may", "might", "must", "than", "then", "so",
    "such", "also", "into", "about", "over", "under", "between", "both", "each", "more",
    "most", "other", "some", "any", "all", "if", "because", "while", "when", "where", "what",
    "how", "there", "here", "them", "us", "one", "two", "s", "t",
}

TOKEN_RE = re.compile(r"[a-zA-Z]+")
SENT_SPLIT_RE = re.compile(r"(?<=[.!?])\s+(?=[A-Z0-9\"'(])")
WS_RE = re.compile(r"\s+")

SHEET_FIELDS = [
    "ann_id", "claim_text", "cited_paper_title", "cited_paper_doi",
    "cited_paper_first_author_year", "cited_paper_passage", "annotator_label",
    "annotator_confidence", "annotator_note", "annotator_name", "annotated_on",
]


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--claims", required=True, help="path to the claims jsonl")
    parser.add_argument(
        "--sources", default=None,
        help="optional path to a sources json list; falls back to per-item year fields",
    )
    parser.add_argument("--fulltext-dir", required=True, help="cached-text directory")
    parser.add_argument(
        "--fulltext-rel-dir", required=True,
        help="repo-relative form of --fulltext-dir, written into the index file",
    )
    parser.add_argument("--suffix", required=True, help='e.g. "v3", "real_v3", or "v2"')
    parser.add_argument("--seed", required=True, type=int, help="shuffle seed for the opaque ids")
    parser.add_argument("--out-dir", default=BASE_DIR, help="output directory")
    parser.add_argument(
        "--sheet-prefix", default="hss_annotation_sheet",
        help='basename prefix before "_<suffix>.csv" for the sheet',
    )
    parser.add_argument(
        "--key-prefix", default="hss_annotation_key",
        help='basename prefix before "_<suffix>.csv" for the key',
    )
    parser.add_argument("--id-prefix", default="ann", help='opaque id prefix, e.g. "ann" or "annr"')
    parser.add_argument(
        "--expected-count", type=int, default=None,
        help="optional safety check: fail unless the claims file holds exactly this many items",
    )
    return parser.parse_args(argv)


def tokenize(text):
    toks = TOKEN_RE.findall(text.lower())
    return {t for t in toks if t not in STOPWORDS and len(t) > 1}


def load_claims(path):
    items = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                items.append(json.loads(line))
    return items


def load_sources(path):
    if not path:
        return {}
    with open(path, "r", encoding="utf-8") as f:
        records = json.load(f)
    return {r["doi"]: r for r in records}


def doi_to_filename(doi):
    return doi.replace(".", "-").replace("/", "_") + ".json"


def load_fulltext_sentences(doi, fulltext_dir, cache):
    """Return the list of (roughly) sentence strings for a cited paper's cached text."""
    if doi in cache:
        return cache[doi]
    path = os.path.join(fulltext_dir, doi_to_filename(doi))
    if not os.path.isfile(path):
        cache[doi] = []
        return []
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    parts = [chunk.get("text", "") for chunk in data.get("chunks", [])]
    full_text = " ".join(parts)
    full_text = WS_RE.sub(" ", full_text).strip()
    sentences = [s.strip() for s in SENT_SPLIT_RE.split(full_text) if s.strip()]
    cache[doi] = sentences
    return sentences


def best_passage(claim_text, doi, fulltext_dir, cache):
    """Score 1-3 sentence windows of the cited paper's cached text against the claim.

    Returns (passage_text_or_marker, best_score).
    """
    sentences = load_fulltext_sentences(doi, fulltext_dir, cache)
    if not sentences:
        return NO_MATCH_MARKER, 0.0

    claim_tokens = tokenize(claim_text)
    if not claim_tokens:
        return NO_MATCH_MARKER, 0.0

    best_score = -1.0
    best_window_text = None
    n = len(sentences)
    for window_size in (1, 2, 3):
        for start in range(0, n - window_size + 1):
            window = sentences[start:start + window_size]
            window_text = " ".join(window)
            window_tokens = tokenize(window_text)
            if not window_tokens:
                continue
            union = claim_tokens | window_tokens
            if not union:
                continue
            overlap = len(claim_tokens & window_tokens) / len(union)
            if overlap > best_score:
                best_score = overlap
                best_window_text = window_text

    if best_window_text is None or best_score < MATCH_THRESHOLD:
        return NO_MATCH_MARKER, max(best_score, 0.0)

    passage = best_window_text
    if len(passage) > MAX_PASSAGE_CHARS:
        cut = passage[:MAX_PASSAGE_CHARS]
        last_space = cut.rfind(" ")
        if last_space > 0:
            cut = cut[:last_space]
        passage = cut.rstrip() + " ..."
    return passage, best_score


def surname(full_name):
    parts = full_name.strip().split()
    return parts[-1] if parts else full_name.strip()


def first_author_year(authors, year):
    surnames = [surname(a) for a in authors] if authors else []
    if not surnames:
        base = "Unknown"
    elif len(surnames) == 1:
        base = surnames[0]
    elif len(surnames) == 2:
        base = f"{surnames[0]} & {surnames[1]}"
    else:
        base = f"{surnames[0]} et al."
    year_str = str(year) if year is not None else "n.d."
    return f"{base}, {year_str}"


def build(args) -> dict:
    """Run the build and write the sheet, key and index. Returns a stats dict for tests."""
    items = load_claims(args.claims)
    if args.expected_count is not None:
        assert len(items) == args.expected_count, (
            f"expected {args.expected_count} claim items, found {len(items)}"
        )
    sources = load_sources(args.sources)

    item_ids = [it["item_id"] for it in items]
    assert len(set(item_ids)) == len(items), "item_id values are not unique"

    shuffled = list(item_ids)
    random.Random(args.seed).shuffle(shuffled)
    width = max(2, len(str(len(shuffled))))
    ann_id_by_item = {
        item_id: f"{args.id_prefix}-{i + 1:0{width}d}" for i, item_id in enumerate(shuffled)
    }

    by_item_id = {it["item_id"]: it for it in items}
    has_expected = any(it.get("expected") for it in items)

    key_rows = []
    sheet_rows = []
    index_map = {}
    fulltext_cache: dict = {}

    n_passage = 0
    n_no_match = 0
    n_withheld = 0

    for item_id, ann_id in ann_id_by_item.items():
        item = by_item_id[item_id]
        chunk_doi = item.get("chunk_doi")
        source_doi = item.get("source_doi")
        cited_doi = chunk_doi if chunk_doi else source_doi
        withheld = chunk_doi is None

        if has_expected:
            key_rows.append({
                "ann_id": ann_id,
                "item_id": item_id,
                "construction_category": item.get("rule", ""),
                "expected_label": "|".join(item["expected"]) if item.get("expected") else "",
                "built_at": item.get("built_at", ""),
            })
        else:
            key_rows.append({"ann_id": ann_id, "item_id": item_id})

        source_rec = sources.get(cited_doi, {})
        year = source_rec.get("year")
        if year is None:
            year = item.get("year") or item.get("cited_year")
        fay = first_author_year(item.get("authors") or [], year)

        if withheld:
            passage = WITHHELD_MARKER
            n_withheld += 1
            paths = []
        else:
            passage, _score = best_passage(
                item["claim"], cited_doi, args.fulltext_dir, fulltext_cache
            )
            if passage == NO_MATCH_MARKER:
                n_no_match += 1
            else:
                n_passage += 1
            paths = [f"{args.fulltext_rel_dir}/{doi_to_filename(cited_doi)}"]

        sheet_rows.append({
            "ann_id": ann_id,
            "claim_text": item["claim"],
            "cited_paper_title": item.get("title", ""),
            "cited_paper_doi": cited_doi,
            "cited_paper_first_author_year": fay,
            "cited_paper_passage": passage,
            "annotator_label": "",
            "annotator_confidence": "",
            "annotator_note": "",
            "annotator_name": "",
            "annotated_on": "",
        })

        index_map[ann_id] = {"cited_paper_doi": cited_doi, "paths": paths}

    def ann_num(ann_id):
        return int(ann_id.rsplit("-", 1)[1])

    key_rows.sort(key=lambda r: ann_num(r["ann_id"]))
    sheet_rows.sort(key=lambda r: ann_num(r["ann_id"]))

    os.makedirs(args.out_dir, exist_ok=True)

    key_fieldnames = (
        ["ann_id", "item_id", "construction_category", "expected_label", "built_at"]
        if has_expected else ["ann_id", "item_id"]
    )
    key_path = os.path.join(args.out_dir, f"{args.key_prefix}_{args.suffix}.csv")
    with open(key_path, "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=key_fieldnames)
        w.writeheader()
        w.writerows(key_rows)

    sheet_path = os.path.join(args.out_dir, f"{args.sheet_prefix}_{args.suffix}.csv")
    with open(sheet_path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=SHEET_FIELDS)
        w.writeheader()
        w.writerows(sheet_rows)

    index_path = os.path.join(args.out_dir, f"source_texts_index_{args.suffix}.json")
    with open(index_path, "w", encoding="utf-8") as f:
        json.dump(index_map, f, ensure_ascii=False, indent=2, sort_keys=True)
        f.write("\n")

    return {
        "n_items": len(sheet_rows),
        "n_passage": n_passage,
        "n_no_match": n_no_match,
        "n_withheld": n_withheld,
        "has_expected": has_expected,
        "key_path": key_path,
        "sheet_path": sheet_path,
        "index_path": index_path,
    }


def main(argv=None):
    args = parse_args(argv)
    stats = build(args)
    print("items:", stats["n_items"])
    print("with a passage shown:", stats["n_passage"])
    print("with the no-match marker:", stats["n_no_match"])
    print("withheld:", stats["n_withheld"])
    print("key carries expected labels:", stats["has_expected"])
    return stats


if __name__ == "__main__":
    main()
