"""Deterministic renderer for the project's chosen citation style.

The writer (`app.services.writing`) and the claim verifier
(`app.services.fulltext.extract_claims_from_document`) both stay author-year, unchanged
by this module. What the author chose in `project.citation_style` (APA, Chicago, MLA,
Harvard, IEEE, Vancouver or a custom label, treated as APA) is applied only here, at two
points: export (`app.api.drafts.export_draft`) and paper chat
(`app.api.paper_chat.chat_with_papers`). Reference entries are built from the project's
own paper metadata (`authors`, `year`, `title`, `journal_name`, `doi`); nothing is
generated by a model.

Two entry points share one core:

* `render_document` walks a Tiptap draft document, using the paragraph's own
  `citationLinks` (the map the writer module produced) to find each citation's position;
* `render_answer` walks a plain-text chat answer, using `fulltext.citation_extents` and
  `fulltext.build_paper_lookup` -- the same span reconstruction and paper lookup the
  claim verifier itself uses, so a rendered number and a verification verdict always
  name the same paper.

Both reduce to the same citation occurrence shape, `(start, end, keys)` within one block
of text: IEEE and Vancouver replace each occurrence with its assigned number(s) in
first-appearance order; every other style (including `custom`) leaves the text
untouched. A reference list, built only from papers actually cited, is always appended
when there is at least one.

Pure and synchronous throughout: no network call, no database session, no write-back to
the draft it was given.
"""

from __future__ import annotations

import copy
import re
from dataclasses import dataclass, field
from typing import Any, Iterator

from pydantic import BaseModel, Field

from app.services.citation_audit import NAME_PARTICLES, citation_spans
from app.services.fulltext import (
    REFERENCE_LIST_HEADING_RE,
    build_paper_lookup,
    citation_extents,
)

#: Styles whose in-text citations are replaced with numbers. Matched case-insensitively
#: against `project.citation_style`; every other value, including `custom`, is rendered
#: as APA-form author-year.
_NUMBERED_STYLES = frozenset({"ieee", "vancouver"})


class RenderedDocument(BaseModel):
    """What `render_document` returns: the rendered Tiptap document (a deep copy, the
    input is never mutated) plus a summary of how many citations were found, rendered
    and left unresolved."""

    content: dict | None = None
    references: list[str] = Field(default_factory=list)
    numbered: bool = False
    found: int = 0
    rendered: int = 0
    unresolved: list[str] = Field(default_factory=list)


class RenderedText(BaseModel):
    """What `render_answer` returns: the rendered markdown answer plus the same summary
    `RenderedDocument` carries."""

    text: str = ""
    references: list[str] = Field(default_factory=list)
    numbered: bool = False
    found: int = 0
    rendered: int = 0
    unresolved: list[str] = Field(default_factory=list)


def _style_key(style: str | None) -> str:
    return (style or "APA").strip().casefold()


def _is_numbered(style: str | None) -> bool:
    return _style_key(style) in _NUMBERED_STYLES


def _normalize_ws(text: str) -> str:
    """Collapse whitespace runs to one space (mirrors
    `app.services.fulltext._doc_normalize_ws`; kept as a separate one-line function here
    rather than imported, since this module takes only three delegations from
    `app.services.fulltext`)."""
    return " ".join((text or "").split())


def _find_all_spans(text: str, snippet: str) -> list[tuple[int, int]]:
    """Every verbatim, non-overlapping ``(start, end)`` occurrence of *snippet* in
    *text*, left to right (mirrors `app.services.fulltext._find_all_spans`; kept as a
    separate function for the same reason as `_normalize_ws` above)."""
    if not snippet:
        return []
    spans: list[tuple[int, int]] = []
    cursor = 0
    while True:
        start = text.find(snippet, cursor)
        if start == -1:
            break
        spans.append((start, start + len(snippet)))
        cursor = start + len(snippet)
    return spans


def _meta(paper: Any, name: str) -> Any:
    """One field off *paper*, whether it is an ORM `Paper`, a SQLAlchemy result row (what
    paper chat holds) or a plain dict."""
    if isinstance(paper, dict):
        return paper.get(name)
    return getattr(paper, name, None)


def _author_display_names(paper: Any) -> list[str]:
    names: list[str] = []
    for author in _meta(paper, "authors") or []:
        if isinstance(author, dict):
            name = author.get("name") or author.get("family") or ""
        else:
            name = str(author or "")
        if name:
            names.append(name)
    return names


def _split_name(raw: str) -> tuple[str, str]:
    """(family, given) from one author name: split at the first
    comma when there is one ("Smith, Jane Q." -> ("Smith", "Jane Q.")); otherwise at the
    last whitespace token, plus any directly preceding lower-case particle from
    `citation_audit.NAME_PARTICLES` ("Teun van Dijk" -> ("van Dijk", "Teun"))."""
    raw = (raw or "").strip()
    if not raw:
        return "", ""
    if "," in raw:
        family, _, given = raw.partition(",")
        return family.strip(), given.strip()
    tokens = raw.split()
    if len(tokens) <= 1:
        return (tokens[0] if tokens else ""), ""
    split_at = len(tokens) - 1
    if split_at >= 1 and tokens[split_at - 1] in NAME_PARTICLES:
        split_at -= 1
    return " ".join(tokens[split_at:]), " ".join(tokens[:split_at])


def _initials(given: str, *, sep: str = " ", period: bool = True) -> str:
    letters = [token[0].upper() for token in given.split() if token]
    if period:
        letters = [f"{letter}." for letter in letters]
    return sep.join(letters)


def _author_apa(family: str, given: str) -> str:
    initials = _initials(given)
    return f"{family}, {initials}" if initials else family


def _author_full_first(family: str, given: str) -> str:
    """'Family, Given' -- Chicago's and MLA's first-author form."""
    return f"{family}, {given}" if given else family


def _author_given_family(family: str, given: str) -> str:
    """'Given Family' -- Chicago's and MLA's subsequent-author form."""
    return f"{given} {family}".strip() if given else family


def _author_harvard(family: str, given: str) -> str:
    initials = _initials(given, sep="")
    return f"{family}, {initials}" if initials else family


def _author_ieee(family: str, given: str) -> str:
    initials = _initials(given)
    return f"{initials} {family}".strip() if initials else family


def _author_vancouver(family: str, given: str) -> str:
    initials = _initials(given, sep="", period=False)
    return f"{family} {initials}".strip() if initials else family


def _join_authors(formatted: list[str], connector: str, comma_before_connector: bool) -> str:
    if not formatted:
        return ""
    if len(formatted) == 1:
        return formatted[0]
    sep = f", {connector} " if comma_before_connector else f" {connector} "
    return ", ".join(formatted[:-1]) + sep + formatted[-1]


Names = list[tuple[str, str]]


def _format_apa(
    authors: Names, title: str, journal: str | None, year: str | None, doi: str | None
) -> str:
    authors_str = _join_authors([_author_apa(f, g) for f, g in authors], "&", True)
    entry = f"{authors_str} ({year or 'n.d.'}). {title}."
    if journal:
        entry += f" {journal}."
    if doi:
        entry += f" https://doi.org/{doi}"
    return entry


def _format_chicago(
    authors: Names, title: str, journal: str | None, year: str | None, doi: str | None
) -> str:
    formatted = [
        _author_full_first(f, g) if i == 0 else _author_given_family(f, g)
        for i, (f, g) in enumerate(authors)
    ]
    authors_str = _join_authors(formatted, "and", True)
    entry = f'{authors_str}. {year or "n.d."}. "{title}."'
    if journal:
        entry += f" {journal}."
    if doi:
        entry += f" https://doi.org/{doi}"
    return entry


def _format_mla(
    authors: Names, title: str, journal: str | None, year: str | None, doi: str | None
) -> str:
    if len(authors) >= 3:
        family, given = authors[0]
        authors_str = f"{_author_full_first(family, given)}, et al"
    else:
        formatted = [
            _author_full_first(f, g) if i == 0 else _author_given_family(f, g)
            for i, (f, g) in enumerate(authors)
        ]
        authors_str = _join_authors(formatted, "and", True)
    doi_part = f"https://doi.org/{doi}" if doi else None
    trailing = [part for part in (journal, year or "n.d.", doi_part) if part]
    entry = f'{authors_str}. "{title}."'
    if trailing:
        entry += " " + ", ".join(trailing) + "."
    return entry


def _format_harvard(
    authors: Names, title: str, journal: str | None, year: str | None, doi: str | None
) -> str:
    authors_str = _join_authors([_author_harvard(f, g) for f, g in authors], "and", False)
    entry = f"{authors_str} ({year or 'n.d.'}) '{title}'"
    entry += f", {journal}." if journal else "."
    if doi:
        entry += f" Available at: https://doi.org/{doi}"
    return entry


def _format_ieee(
    number: int, authors: Names, title: str, journal: str | None, year: str | None, doi: str | None
) -> str:
    authors_str = _join_authors([_author_ieee(f, g) for f, g in authors], "and", False)
    entry = f'[{number}] {authors_str}, "{title},"'
    trailing = [part for part in (journal, year) if part]
    entry += (" " + ", ".join(trailing) + ".") if trailing else "."
    if doi:
        entry += f" doi: {doi}."
    return entry


def _format_vancouver(
    number: int, authors: Names, title: str, journal: str | None, year: str | None, doi: str | None
) -> str:
    authors_str = ", ".join(_author_vancouver(f, g) for f, g in authors)
    entry = f"{number}. {authors_str}. {title}."
    if journal:
        entry += f" {journal}."
    if year:
        entry += f" {year}."
    if doi:
        entry += f" doi:{doi}."
    return entry


def _format_entry(number: int | None, paper: Any, style: str) -> str:
    """One reference-list entry for *paper*, in *style*. Only
    `authors`, `year`, `title`, `journal_name` and `doi` are read; a missing element is
    omitted, never invented."""
    authors = [_split_name(name) for name in _author_display_names(paper)]
    title = _meta(paper, "title") or ""
    journal = _meta(paper, "journal_name") or None
    raw_year = _meta(paper, "year")
    year = str(raw_year) if raw_year else None
    doi = _meta(paper, "doi") or None

    key = _style_key(style)
    if key == "chicago":
        return _format_chicago(authors, title, journal, year, doi)
    if key == "mla":
        return _format_mla(authors, title, journal, year, doi)
    if key == "harvard":
        return _format_harvard(authors, title, journal, year, doi)
    if key == "ieee":
        return _format_ieee(number or 1, authors, title, journal, year, doi)
    if key == "vancouver":
        return _format_vancouver(number or 1, authors, title, journal, year, doi)
    return _format_apa(authors, title, journal, year, doi)  # apa, custom, anything else


def _sort_key(paper: Any) -> tuple[str, int, str]:
    names = _author_display_names(paper)
    family = _split_name(names[0])[0] if names else ""
    return (family.casefold(), _meta(paper, "year") or 0, (_meta(paper, "title") or "").casefold())


def _build_references(
    cited_keys_in_order: list[str], paper_lookup: dict, style: str, numbered: bool
) -> list[str]:
    """Reference-list entries for the papers actually cited, deduplicated, in
    first-appearance order for a numbered style or sorted by family/year/title
    otherwise."""
    seen: list[str] = []
    for key in cited_keys_in_order:
        if key not in seen:
            seen.append(key)
    if not seen:
        return []
    if numbered:
        return [_format_entry(i, paper_lookup[key], style) for i, key in enumerate(seen, start=1)]
    ordered = sorted(seen, key=lambda k: _sort_key(paper_lookup[k]))
    return [_format_entry(None, paper_lookup[key], style) for key in ordered]


@dataclass
class _Occurrence:
    """One citation occurrence: `(start, end, keys)` within one block of text.
    ``rendered`` is set only for a lone occurrence built straight from
    `fulltext.citation_extents`: the audit's own,
    already-balanced form of this one member, held in reserve for when ``start:end``
    itself is not balanced -- true of a semicolon-group member whose neighbour is
    keyless, which blocks the merge that would otherwise widen the slice back to the
    whole, balanced group. Left empty by a
    merge and by a link-covered occurrence, both of which keep a balanced slice already."""

    start: int
    end: int
    keys: list[str] = field(default_factory=list)
    rendered: str = ""


def _resolvable_keys(occurrence: _Occurrence, paper_lookup: dict) -> list[str]:
    return [key for key in occurrence.keys if key in paper_lookup]


def _is_balanced(text: str) -> bool:
    """True when every ``(``/``)`` and ``[``/``]`` in *text* is matched, in order
    (mirrors `app.services.fulltext._is_bracket_balanced`; kept as a separate function
    here for the same reason as `_normalize_ws` above)."""
    depth_paren = depth_bracket = 0
    for character in text:
        if character == "(":
            depth_paren += 1
        elif character == ")":
            depth_paren -= 1
            if depth_paren < 0:
                return False
        elif character == "[":
            depth_bracket += 1
        elif character == "]":
            depth_bracket -= 1
            if depth_bracket < 0:
                return False
    return depth_paren == 0 and depth_bracket == 0


def _balanced_or(raw: str, fallback: str) -> str:
    """*raw* when it is bracket-balanced, and *fallback* otherwise. Shared by
    `_unresolved_text`, which has a source
    position to slice *raw* from, and the stale-text path in `_draft_occurrences`, which
    does not. Nothing is ever deleted by this -- only the string a human is shown."""
    return raw if _is_balanced(raw) else (fallback or raw)


def _trim_to_balanced(text: str) -> str:
    """*text* with characters trimmed from the right until what remains is
    bracket-balanced, or *text* itself if trimming would empty it out first. The only
    fallback available for
    a stale link's own ``citation_text``, which -- unlike an occurrence built from
    `citation_extents` -- carries no position in the paragraph to look an audit-rendered
    form up by."""
    trimmed = text
    while trimmed and not _is_balanced(trimmed):
        trimmed = trimmed[:-1]
    return trimmed or text


def _unresolved_text(text: str, occurrence: _Occurrence) -> str:
    """The text `unresolved` reports for *occurrence*: its raw slice when that is
    bracket-balanced, and its own audit-rendered form otherwise. Nothing is ever
    deleted by this -- only the string a human is shown."""
    raw = text[occurrence.start : occurrence.end]
    return _balanced_or(raw, occurrence.rendered)


def _fully_resolved(occurrence: _Occurrence, resolved: list[str]) -> bool:
    """Whether every key *occurrence* carries is resolved. A merged citation with one
    member absent from the library is rendered
    only when *all* of its members resolve; otherwise the whole occurrence is left
    exactly as written and reported in `unresolved`, rather than silently naming only
    the source(s) that did resolve."""
    return bool(resolved) and len(resolved) == len(occurrence.keys)


_SEMICOLON_GAP_RE = re.compile(r"^\s*;\s*$")


def _merge_semicolon_adjacent(text: str, occurrences: list[_Occurrence]) -> list[_Occurrence]:
    """Two adjacent occurrences separated only by ``;`` and whitespace merge into one,
    carrying both occurrences' keys in order: the shape
    `fulltext._audit_span_units` reconstructs a semicolon-delimited group into, one
    member per unit ("(Storch, 2018; Lee, 2019)" is two units before this step), so a
    single group is numbered and replaced as the one citation it renders as.

    Neither side of a merge may be keyless.
    A citation no link covers reaches here with ``keys == []`` (`_draft_occurrences`'s
    own fallback for a citation the writer's map never touched); merging it into an
    adjacent, resolvable occurrence made the merged occurrence's key count equal its
    resolved count by accident, so `_fully_resolved` accepted it and replaced the whole
    merged range -- keyless member's text included -- with the resolvable member's
    number alone. A keyless occurrence now always stays on its own, exactly as if it had
    no semicolon-adjacent neighbour at all."""
    if not occurrences:
        return []
    ordered = sorted(occurrences, key=lambda o: (o.start, o.end))
    merged: list[_Occurrence] = [ordered[0]]
    for occurrence in ordered[1:]:
        last = merged[-1]
        can_merge = (
            last.keys
            and occurrence.keys
            and _SEMICOLON_GAP_RE.match(text[last.end : occurrence.start])
        )
        if can_merge:
            merged[-1] = _Occurrence(
                start=last.start, end=occurrence.end, keys=last.keys + occurrence.keys
            )
        else:
            merged.append(occurrence)
    return merged


def _assign_numbers(blocks: list[list[_Occurrence]], paper_lookup: dict) -> dict[str, int]:
    """key -> number, in first-appearance order: blocks in document order, occurrences by
    start offset, keys within an occurrence in their own order.
    An occurrence that will be left unresolved (one of its keys is not in the library)
    reserves no number for any of its keys, so a
    citation rendered nowhere never leaves a gap in the numbering."""
    numbers: dict[str, int] = {}
    for occurrences in blocks:
        for occurrence in sorted(occurrences, key=lambda o: (o.start, o.end)):
            resolved = _resolvable_keys(occurrence, paper_lookup)
            if not _fully_resolved(occurrence, resolved):
                continue
            for key in resolved:
                if key not in numbers:
                    numbers[key] = len(numbers) + 1
    return numbers


def _format_numbers(numbers: list[int], style_key: str) -> str:
    if style_key == "vancouver":
        return "[" + ", ".join(str(n) for n in numbers) + "]"
    return ", ".join(f"[{n}]" for n in numbers)  # ieee


def _narrative_replace_range(text: str, occurrence: _Occurrence) -> tuple[int, int]:
    """The range actually replaced for *occurrence*: a narrative
    citation keeps its author, only the parenthesised year onward is replaced ("Smith et
    al. (2020) showed" -> "Smith et al. [1] showed"); a purely parenthetical citation is
    replaced whole ("(Smith, 2020)" -> "[1]")."""
    snippet = text[occurrence.start : occurrence.end]
    paren = snippet.find("(")
    if paren > 0:
        return occurrence.start + paren, occurrence.end
    return occurrence.start, occurrence.end


