#: A markdown heading line ("## References", "# Bibliography", ...): matched the same
#: way `_drop_existing_reference_section` matches a Tiptap heading node, just applied to
#: a `#`-prefixed line of plain text instead of a node's own text.
_MARKDOWN_HEADING_LINE_RE = re.compile(r"(?m)^#{1,6}[ \t]+(.+?)[ \t]*$")


def _strip_trailing_reference_section(text: str) -> str:
    """Drop a reference-list heading and the block up to the next heading from *text*.
    Chat rule 5 tells the model not to write its own references section; when it
    does anyway, this keeps the answer to one, ours -- exactly what
    `_drop_existing_reference_section` already does for a draft document, including
    keeping whatever follows the next heading, rather than dropping
    everything to the end of the answer, which would delete a genuine section (such as
    "## Limitations") that happened to come after the model's own reference list."""
    matches = list(_MARKDOWN_HEADING_LINE_RE.finditer(text))
    for index, match in enumerate(matches):
        if not REFERENCE_LIST_HEADING_RE.match(match.group(1).strip()):
            continue
        if index + 1 < len(matches):
            following = text[matches[index + 1].start() :]
            return (text[: match.start()].rstrip() + "\n\n" + following).rstrip()
        return text[: match.start()].rstrip()
    return text


def _chat_occurrences(text: str) -> list[_Occurrence]:
    spans = citation_spans(text)
    occurrences: list[_Occurrence] = []
    for start, end, rendered in citation_extents(text):
        keys: list[str] = []
        for position, surname, year, _label in spans:
            if start <= position < end and year is not None:
                keys = [f"{surname.split()[-1].lower()}_{year}"]
                break
        occurrences.append(_Occurrence(start=start, end=end, keys=keys, rendered=rendered))
    return occurrences


def render_answer(text: str, papers: list, style: str) -> RenderedText:
    """Render *text* (a paper-chat answer, author-year in text) in the project's chosen
    *style*. Author-year styles return the text unchanged, plus
    a references section built from *papers*' own metadata; IEEE and Vancouver also
    replace each citation with its assigned number(s)."""
    numbered = _is_numbered(style)
    if not text or not papers:
        return RenderedText(text=text or "", numbered=numbered)

    paper_lookup = build_paper_lookup(list(papers))
    if not paper_lookup:
        return RenderedText(text=text, numbered=numbered)

    style_key = _style_key(style)
    occurrences = _merge_semicolon_adjacent(text, _chat_occurrences(text))
    found = len(occurrences)
    numbers = _assign_numbers([occurrences], paper_lookup) if numbered else {}

    cited_keys_in_order: list[str] = []
    unresolved: list[str] = []
    edits: list[tuple[int, int, str]] = []
    rendered_count = 0

    for occurrence in sorted(occurrences, key=lambda o: (o.start, o.end)):
        resolved = _resolvable_keys(occurrence, paper_lookup)
        if not _fully_resolved(occurrence, resolved):
            unresolved.append(_unresolved_text(text, occurrence))
            continue
        for key in resolved:
            if key not in cited_keys_in_order:
                cited_keys_in_order.append(key)
        if not numbered:
            continue
        nums = [numbers[key] for key in resolved]
        start, end = _narrative_replace_range(text, occurrence)
        edits.append((start, end, _format_numbers(nums, style_key)))
        rendered_count += 1

    for start, end, replacement in sorted(edits, key=lambda e: e[0], reverse=True):
        text = text[:start] + replacement + text[end:]

    references = _build_references(cited_keys_in_order, paper_lookup, style, numbered)
    if references:
        text = _strip_trailing_reference_section(text)
        text = text.rstrip() + "\n\n## References\n" + "\n".join(references)

    return RenderedText(
        text=text,
        references=references,
        numbered=numbered,
        found=found,
        rendered=rendered_count,
        unresolved=unresolved,
    )


# --------------------------------------------------------------------------------------
# Draft path: the paragraph's own citationLinks. Duplicated
# here, in miniature, rather than imported: `fulltext`'s own paragraph walk
# (`_iter_paragraph_nodes`, `_CONTAINER_NODE_TYPES`) is read-only text extraction, while
# this module also needs each citation's own text-node offsets to mutate a single node in
# place, so it keeps its own copy of the recursion rule instead of half-reusing fulltext's.
# --------------------------------------------------------------------------------------

#: Node types whose own ``content`` holds further nodes to walk into, so a citation
#: inside a bulleted list or a blockquote is found exactly like a top-level paragraph
#: (mirrors `fulltext._CONTAINER_NODE_TYPES`).
_CONTAINER_NODE_TYPES = frozenset({"bulletList", "orderedList", "listItem", "blockquote"})


def _iter_paragraph_nodes(nodes: list[dict]) -> Iterator[dict]:
    for node in nodes:
        if not isinstance(node, dict):
            continue
        node_type = node.get("type")
        if node_type == "paragraph":
            yield node
        elif node_type in _CONTAINER_NODE_TYPES:
            yield from _iter_paragraph_nodes(
                [n for n in (node.get("content") or []) if isinstance(n, dict)]
            )


def _node_text(node: dict) -> str:
    """Plain text of a heading or paragraph node's own direct text children (no
    recursion: a heading or paragraph's content is inline nodes, not further blocks)."""
    return "".join(
        c.get("text") or ""
        for c in (node.get("content") or [])
        if isinstance(c, dict) and c.get("type") == "text"
    )


def _paragraph_text_nodes(node: dict) -> list[dict]:
    return [
        c for c in (node.get("content") or []) if isinstance(c, dict) and c.get("type") == "text"
    ]


def _node_offsets(text_nodes: list[dict]) -> list[tuple[int, int]]:
    offsets: list[tuple[int, int]] = []
    cursor = 0
    for node in text_nodes:
        length = len(node.get("text") or "")
        offsets.append((cursor, cursor + length))
        cursor += length
    return offsets


def _containing_node_index(offsets: list[tuple[int, int]], start: int, end: int) -> int | None:
    for index, (node_start, node_end) in enumerate(offsets):
        if node_start <= start and end <= node_end:
            return index
    return None


def _drop_existing_reference_section(nodes: list[dict]) -> list[dict]:
    """Drop an existing reference section -- a heading matching
    `fulltext.REFERENCE_LIST_HEADING_RE`, and everything up to the next heading -- so
    export never shows two reference lists."""
    for index, node in enumerate(nodes):
        if not isinstance(node, dict) or node.get("type") != "heading":
            continue
        if not REFERENCE_LIST_HEADING_RE.match(_node_text(node).strip()):
            continue
        end = len(nodes)
        for later in range(index + 1, len(nodes)):
            if isinstance(nodes[later], dict) and nodes[later].get("type") == "heading":
                end = later
                break
        return nodes[:index] + nodes[end:]
    return nodes


def _draft_occurrences(
    paragraph_text: str, links: list[dict]
) -> tuple[list[_Occurrence], list[str]]:
    """Occurrences from one paragraph's own ``citationLinks``, plus the bare
    ``citation_text`` of any link whose text no longer occurs verbatim, plus a citation
    `fulltext.citation_extents` finds that no link covers at all: every
    citation in a draft written before citation links existed, and any citation typed
    into the editor after generation. A link counts only while its own ``sentence``
    still occurs in the paragraph, whitespace normalised; a link whose sentence has gone
    stale is ignored outright, exactly as `fulltext.extract_claims_from_document` ignores
    it. A citation_text shared by two links (rendered twice) is allocated to its own
    occurrence left to right.

    A `citation_extents` span already claimed by an occurrence above is skipped by
    position, not by text: comparing
    normalised text instead, keyed on every link's own ``citation_text``, made a second,
    distinct occurrence of the same wording (a source cited twice in one paragraph, only
    the first citation linked) look "already accounted for" and drop it silently. Only a
    stale link's own text is still tracked by text, since a stale link has no position at
    all to compare by, and the whitespace it went stale over (a link's ``citation_text``
    normalised-equal to the paragraph's own spelling, but not verbatim) is exactly the
    shape a position comparison cannot catch.

    Every occurrence built here carries ``rendered``, the covering `citation_extents`
    span's own already-balanced text: a link-derived occurrence gets it from the extent
    overlapping its own
    ``start``/``end``. A stale text has no position to look an extent up by at all, so it
    is balance-checked against `_trim_to_balanced` instead, which needs none: the one
    shape a `citation_text` has been seen to fail balance in is one bracket past the
    citation's own close, from an enclosing parenthetical the model's own text ran into,
    and trimming from the right recovers exactly that with no audit lookup required.
    Neither path changes which citation resolves; both only give `render_document`'s
    ``unresolved`` a string that is always bracket-balanced, matching what
    `fulltext.extract_claims_from_document` already reports for the same citation."""
    paragraph_norm = _normalize_ws(paragraph_text)
    occurrences: list[_Occurrence] = []
    stale_texts: list[str] = []
    stale_norm_texts: set[str] = set()
    spans_cache: dict[str, list[tuple[int, int]]] = {}
    next_index: dict[str, int] = {}
    extents = citation_extents(paragraph_text)

    def _covering_extent_text(start: int, end: int) -> str:
        for e_start, e_end, rendered in extents:
            if e_start < end and start < e_end:
                return rendered
        return ""

    for link in links:
        sentence_norm = _normalize_ws(link.get("sentence") or "")
        if not sentence_norm or sentence_norm not in paragraph_norm:
            continue  # stale: ignored, not counted at all
        citation_text = link.get("citation_text") or ""
        if citation_text not in spans_cache:
            spans_cache[citation_text] = _find_all_spans(paragraph_text, citation_text)
        spans = spans_cache[citation_text]
        index = next_index.get(citation_text, 0)
        if index >= len(spans):
            # citation_text no longer occurs verbatim: counted, unresolved, no position.
            stale_texts.append(_balanced_or(citation_text, _trim_to_balanced(citation_text)))
            stale_norm_texts.add(_normalize_ws(citation_text))
            continue
        next_index[citation_text] = index + 1
        start, end = spans[index]
        keys = [key for key in (link.get("keys") or []) if key]
        rendered = _covering_extent_text(start, end)
        occurrences.append(_Occurrence(start=start, end=end, keys=keys, rendered=rendered))

    for start, end, rendered in extents:
        if any(o.start < end and start < o.end for o in occurrences):
            continue  # already accounted for above, by position
        if _normalize_ws(rendered) in stale_norm_texts:
            continue  # the paragraph's own respelling of a link whose text went stale
        occurrences.append(_Occurrence(start=start, end=end, keys=[], rendered=rendered))

    return occurrences, stale_texts


def render_document(content: dict | None, papers: list, style: str) -> RenderedDocument:
    """Render *content* (a Tiptap draft document, author-year in text) in the project's
    chosen *style*. The input is deep-copied and never
    written back. Empty content, or a project with no papers, is returned unchanged with
    no reference section."""
    numbered = _is_numbered(style)
    if not isinstance(content, dict) or not papers:
        copied = copy.deepcopy(content) if isinstance(content, dict) else content
        return RenderedDocument(content=copied, numbered=numbered)

    paper_lookup = build_paper_lookup(list(papers))
    if not paper_lookup:
        return RenderedDocument(content=copy.deepcopy(content), numbered=numbered)

    style_key = _style_key(style)
    doc = copy.deepcopy(content)
    original_top_nodes = [n for n in (doc.get("content") or []) if isinstance(n, dict)]
    top_nodes = _drop_existing_reference_section(original_top_nodes)
    had_existing_reference_section = len(top_nodes) != len(original_top_nodes)

    found = 0
    unresolved: list[str] = []
    paragraphs: list[tuple[list[dict], list[tuple[int, int]], str, list[_Occurrence]]] = []

    for node in _iter_paragraph_nodes(top_nodes):
        text_nodes = _paragraph_text_nodes(node)
        paragraph_text = "".join(n.get("text") or "" for n in text_nodes)
        if not paragraph_text.strip():
            continue
        links = (node.get("attrs") or {}).get("citationLinks") or []
        raw_occurrences, stale_texts = _draft_occurrences(paragraph_text, links)
        occurrences = _merge_semicolon_adjacent(paragraph_text, raw_occurrences)
        found += len(occurrences) + len(stale_texts)
        unresolved.extend(stale_texts)
        paragraphs.append((text_nodes, _node_offsets(text_nodes), paragraph_text, occurrences))

    numbers = _assign_numbers([p[3] for p in paragraphs], paper_lookup) if numbered else {}

    cited_keys_in_order: list[str] = []
    rendered_count = 0

    for text_nodes, offsets, paragraph_text, occurrences in paragraphs:
        edits: dict[int, list[tuple[int, int, str]]] = {}
        for occurrence in occurrences:
            resolved = _resolvable_keys(occurrence, paper_lookup)
            if not _fully_resolved(occurrence, resolved):
                unresolved.append(_unresolved_text(paragraph_text, occurrence))
                continue
            for key in resolved:
                if key not in cited_keys_in_order:
                    cited_keys_in_order.append(key)
            if not numbered:
                continue
            start, end = _narrative_replace_range(paragraph_text, occurrence)
            node_index = _containing_node_index(offsets, start, end)
            if node_index is None:
                # An occurrence straddling two text nodes cannot be safely rewritten.
                unresolved.append(_unresolved_text(paragraph_text, occurrence))
                continue
            nums = [numbers[key] for key in resolved]
            local_start, local_end = start - offsets[node_index][0], end - offsets[node_index][0]
            edits.setdefault(node_index, []).append(
                (local_start, local_end, _format_numbers(nums, style_key))
            )
            rendered_count += 1

        for node_index, node_edits in edits.items():
            target = text_nodes[node_index]
            new_text = target.get("text") or ""
            for local_start, local_end, replacement in sorted(
                node_edits, key=lambda e: e[0], reverse=True
            ):
                new_text = new_text[:local_start] + replacement + new_text[local_end:]
            target["text"] = new_text

    references = _build_references(cited_keys_in_order, paper_lookup, style, numbered)
    # Whether to append the generated list and whether to
    # drop the document's own existing reference section are two different decisions.
    # Appending happens whenever there is a generated list to append -- a draft with no
    # reference section of its own (every draft the writer produces) must not export
    # with no list to read a rendered number against, just because one citation stayed
    # unresolved. Dropping the author's own existing section is the one that stays
    # gated on `unresolved`: it is safe only when the generated list is about to replace
    # it entirely, since a citation that resolved to a key absent from the library, or
    # one a link never covered at all, means the generated list covers only some of what
    # the renderer found, and dropping the author's section would silently delete their
    # entry for the rest.
    if references and (not had_existing_reference_section or not unresolved):
        heading_text = {"type": "text", "text": "References"}
        top_nodes.append(
            {"type": "heading", "attrs": {"level": 2}, "content": [heading_text]}
        )
        top_nodes.extend(
            {"type": "paragraph", "content": [{"type": "text", "text": entry}]}
            for entry in references
        )
        doc["content"] = top_nodes
    elif had_existing_reference_section:
        # The existing section (and everything after it) is kept, untouched, until
        # every citation the renderer found resolves.
        doc["content"] = original_top_nodes
    else:
        doc["content"] = top_nodes

    return RenderedDocument(
        content=doc,
        references=references,
        numbered=numbered,
        found=found,
        rendered=rendered_count,
        unresolved=unresolved,
    )
